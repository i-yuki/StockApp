create table public.item_groups (
  id bigint generated by default as identity not null,
  name character varying null,
  created_at timestamp with time zone not null default now(),
  order_number integer not null default 1000,
  user_id uuid null default auth.uid (),
  constraint item_group_pkey primary key (id)
) TABLESPACE pg_default;

create table public.items (
  id bigint generated by default as identity not null,
  item_groups_id bigint not null,
  name character varying not null,
  created_at timestamp with time zone not null default now(),
  order_number integer not null default 1000,
  user_id uuid null default auth.uid (),
  constraint items_pkey primary key (id),
  constraint items_item_groups_id_fkey foreign KEY (item_groups_id) references item_groups (id)
) TABLESPACE pg_default;

create table public.memos (
  id bigint generated by default as identity not null,
  created_at timestamp with time zone not null default now(),
  memo text not null,
  order_number integer not null default 1000,
  user_id uuid null default auth.uid (),
  constraint memos_pkey primary key (id)
) TABLESPACE pg_default;

create table public.past_stocks (
  id bigint generated by default as identity not null,
  item_id bigint null,
  stock_type integer null,
  quantity integer null,
  memo text null,
  created_at timestamp with time zone not null default now(),
  user_id uuid null default auth.uid (),
  constraint past_stocks_pkey primary key (id)
) TABLESPACE pg_default;

create table public.stocks (
  id bigint generated by default as identity not null,
  item_id bigint null,
  stock_type integer null,
  quantity integer null,
  memo text null,
  created_at timestamp with time zone not null default now(),
  lock_flag boolean null default false,
  user_id uuid null default auth.uid (),
  constraint stocks_pkey primary key (id),
  constraint stocks_item_id_fkey foreign KEY (item_id) references items (id)
) TABLESPACE pg_default;

CREATE POLICY "Enable all access for item_groups" ON item_groups FOR ALL TO authenticated USING (auth.uid() = user_id) WITH CHECK (auth.uid() = user_id);
CREATE POLICY "Enable all access for items" ON items FOR ALL TO authenticated USING (auth.uid() = user_id) WITH CHECK (auth.uid() = user_id);
CREATE POLICY "Enable all access for memos" ON memos FOR ALL TO authenticated USING (auth.uid() = user_id) WITH CHECK (auth.uid() = user_id);
CREATE POLICY "Enable all access for past_stocks" ON past_stocks FOR ALL TO authenticated USING (auth.uid() = user_id) WITH CHECK (auth.uid() = user_id);
CREATE POLICY "Enable all access for stocks" ON stocks FOR ALL TO authenticated USING (auth.uid() = user_id) WITH CHECK (auth.uid() = user_id);

CREATE OR REPLACE view public.stock_view
with
  (security_invoker = on) as
select
  item_id,
  sum(quantity) as sum_qty
from
  stocks
where
  lock_flag = false
group by
  item_id;

CREATE OR REPLACE VIEW public.item_stocks
WITH
  (security_invoker = on) AS
SELECT
  items.item_groups_id as group_id,
  items.id as item_id,
  items.name as item_name,
  COALESCE(stock_view.sum_qty, 0) as qty
FROM items
  LEFT JOIN stock_view on items.id = stock_view.item_id
ORDER BY items.order_number;


CREATE OR REPLACE FUNCTION item_quantity_history(p_item_id BIGINT)
RETURNS TABLE(quantity int, memo text, created_at timestamptz) AS 
$$
  SELECT quantity, memo, created_at FROM stocks
    WHERE item_id = p_item_id AND stock_type IN (1, 2)
  UNION ALL
  SELECT quantity, memo, created_at FROM past_stocks
    WHERE item_id = p_item_id AND stock_type IN (1, 2)
  ORDER BY created_at DESC;
$$ LANGUAGE sql;
